    private void Display() {
        //displays all the details for the passport
        ApplicantManager am = new ApplicantManager();
        SmartIDManager sm = new SmartIDManager();

        String name = "" + am.getApplicant(ID).getFirstName()
                + am.getApplicant(ID).getMiddleName();

        RetrieveSmartIDTable.add(ID, this);
        RetrieveSmartIDTable.add(name, this);
        RetrieveSmartIDTable.add(am.getApplicant(ID).getSurname(), this);
        ImageIcon icon1 = new ImageIcon(sm.getSmartID(ID)
                .getBirthCertificate());
        RetrieveSmartIDTable.setValueAt(icon1, 1, 4);
        ImageIcon icon2 = new ImageIcon(sm.getSmartID(ID).getParentIDNumber());
        RetrieveSmartIDTable.setValueAt(icon2, 1, 5);
        ImageIcon icon3 = new ImageIcon(sm.getSmartID(ID)
                .getProofOfResidence());
        RetrieveSmartIDTable.setValueAt(icon3, 1, 6);
    }
