    //adds booking to database
    private void ContinueButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ContinueButtonActionPerformed
        if (BirthCertificate.equals(null) && CopyID.equals(null)) {
            UnabridgedBirthCertificatesManager um
                    = new UnabridgedBirthCertificatesManager();
            um.addUnabridgedBirthCertificate(ID, ParentID.getImage());
            
            this.dispose();
            ActionPerformedScreen eng = new ActionPerformedScreen();
            eng.setVisible(true);
            //changes the screen when the continue button is clicked
        } else {
            if (CopyID.equals(null)) {
                SmartIDManager sm = new SmartIDManager();
                sm.addSmartID(ID, ParentID.getImage(),
                        BirthCertificate.getImage(),
                        ProofOfResidence.getImage());
                
                this.dispose();
                ActionPerformedScreen eng = new ActionPerformedScreen();
                eng.setVisible(true);
                //changes the screen when the continue button is clicked
            } else {
                if (ParentID.equals(null)) {
                    PassportManager pm = new PassportManager();
                    pm.addPassport(ID, CopyID.getImage());
                   
                    this.dispose();
                    ActionPerformedScreen eng = new ActionPerformedScreen();
                    eng.setVisible(true);
                    //changes the screen when the continue button is clicked
                } else {
                    String error = "Unable to retrieve type of Booking "
                            + "(SmartID, Passport, UnabridgedBirthCertificate)";
                    ErrorScreen eng = new ErrorScreen(error);
                    eng.setVisible(true);
                }
            }
        }
    }//GEN-LAST:event_ContinueButtonActionPerformed

