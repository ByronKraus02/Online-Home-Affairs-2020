    private void Display() {
        //enters the available times to be selected
        DateTimeFormatter dtf = DateTimeFormatter.ofPattern("EEE dd MMMM");
        LocalDateTime now = LocalDateTime.now();
        now = now.plusDays(3);
        String Date = dtf.format(now);
        AppointmentManager am = new AppointmentManager();
        String[] Hours = {"10:00", "11:00", "12:00", "14:00", "16:00"};
        String[] newHours = am.checkArray(Hours, Date);
        int count = 0;

        if (BirthCertificate.equals(null) && CopyID.equals(null)) {
            for (int i = 0; i < newHours.length; i++) {
                SelectBookingTable.add(Date, this);
                SelectBookingTable.add(newHours[count], this);
                count++;
            }
        } else {
            if (CopyID.equals(null)) {
                for (int i = 0; i < newHours.length; i++) {
                    SelectBookingTable.add(Date, this);
                    SelectBookingTable.add(newHours[count], this);
                    count++;
                }
            } else {
                if (ParentID.equals(null)) {
                    for (int i = 0; i < newHours.length; i++) {
                        SelectBookingTable.add(Date, this);
                        SelectBookingTable.add(newHours[count], this);
                        count++;
                    }
                } else {
                    String error = "Unable to retrieve type of Booking "
                            + "(SmartID, Passport, UnabridgedBirthCertificate)";
                    ErrorScreen eng = new ErrorScreen(error);
                    eng.setVisible(true);
                }
            }
        }
    }
