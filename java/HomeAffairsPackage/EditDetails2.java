    //checks the new data
    private void cellNumberFieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_cellNumberFieldFocusLost
        ApplicantManager am = new ApplicantManager();
        if (cellNumberField.getText().length() != 10 
                || !(cellNumberField.getText().matches("\\d+")) 
                || cellNumberField.getText().charAt(0) != '0') {
            
            cellNumberField.setText(am.getApplicant(id).getCellNumber());
        }
    }//GEN-LAST:event_cellNumberFieldFocusLost

    //checks the new data
    private void emailFieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_emailFieldFocusLost
        ApplicantManager am = new ApplicantManager();
        if ((emailField.getText().compareTo("@") > 1) 
                || !(emailField.getText().compareTo(".") > 1)) {
           
            emailField.setText(am.getApplicant(id).getEmail());
        }
    }//GEN-LAST:event_emailFieldFocusLost

