    // Screen changes once the continue button is clicked and updates database
    private void ContinueButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ContinueButtonActionPerformed
        ApplicantManager am = new ApplicantManager();
        //each option is checked and changed values are updated
        if (FullNameCheckBox.isSelected()) {
            am.getApplicant(id).setFirstName(FullNameField.getText());
            am.setName(FullNameField.getText(), id);
        }
        if (MiddleNameCheckbox.isSelected()) {
            am.getApplicant(id).setMiddleName(middleNameField.getText());
            am.setMiddleName(middleNameField.getText(), id);
        }
        if (SurnameCheckBox.isSelected()) {
            am.getApplicant(id).setSurname(surnameField.getText());
            am.setSurname(surnameField.getText(), id);
        }
        if (CellNumberCheckBox.isSelected()) {
            am.getApplicant(id).setCellNumber(cellNumberField.getText());
            am.setCellNumber(cellNumberField.getText(), id);
        }
        if (EmailCheckBox.isSelected()) {
            am.getApplicant(id).setEmail(emailField.getText());
            am.setEmail(emailField.getText(), id);
        }

        new ActionPerformedScreen().setVisible(true);
    }//GEN-LAST:event_ContinueButtonActionPerformed

