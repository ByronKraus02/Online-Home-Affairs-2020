    // Screen changes once the continue button is clicked and the correct ID
    //is entered
    private void ContinueButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ContinueButtonActionPerformed
        ApplicantManager am = new ApplicantManager();
        int pos = am.checkApplicantID(IDField.getText());
        if (pos != -1) {
            this.dispose();
            Passport2 eng = new Passport2(IDField.getText(),
                 FullNameField.getText(), SurnameField.getText());
        eng.setVisible(true);
        } else {
            IncorrectIDLabel.setText("Incorrect ID");
            IncorrectIDLabel.setForeground(Color.red);
        }
    }//GEN-LAST:event_ContinueButtonActionPerformed

