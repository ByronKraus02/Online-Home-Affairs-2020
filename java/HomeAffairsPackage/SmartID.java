    //changes the screen when the continue button is clicked
    private void ContinueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ContinueActionPerformed
        ApplicantManager am = new ApplicantManager();
        int pos = am.checkApplicantID(IDField.getText());
        if(am.checkApplicantID(IDField.getText()) != -1 && am.checkApplicantName
        (pos, FirstNameField.getText())){
            //checks if applicant is first time user
            if(ClickBoxCheckBox.isSelected()) {
                this.dispose();
                SmartID3 eng = new SmartID3(IDField.getText(), 
                        FirstNameField.getText(), SurnameField.getText());
                eng.setVisible(true);
            } else {
                this.dispose();
                SmartID2 eng = new SmartID2(IDField.getText(), 
                        FirstNameField.getText(), SurnameField.getText());
                eng.setVisible(true);
            }
        } else {
            IncorrectLabel.setText("Incorrect details");
            IncorrectLabel.setForeground(Color.red);
        }
    }//GEN-LAST:event_ContinueActionPerformed

